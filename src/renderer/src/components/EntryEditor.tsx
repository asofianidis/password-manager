import { useEffect, useMemo, useRef, useState } from 'react'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { Wand2 } from 'lucide-react'
import type { EntryInput, VaultEntry } from '@shared/types'
import { api, queries } from '@renderer/lib/api'
import { MOD, isMod } from '@renderer/lib/keys'
import { toast } from '@renderer/lib/toast'
import {
  Button,
  Checkbox,
  ErrorText,
  Field,
  Input,
  Kbd,
  Monogram,
  PasswordInput,
  StrengthMeter,
  Textarea
} from './ui'

const EMPTY: EntryInput = {
  title: '',
  username: '',
  password: '',
  url: '',
  notes: '',
  totp: '',
  folder: '',
  favorite: false
}

function useDebounced<T>(value: T, delay: number): T {
  const [debounced, setDebounced] = useState(value)
  useEffect(() => {
    const timer = setTimeout(() => setDebounced(value), delay)
    return () => clearTimeout(timer)
  }, [value, delay])
  return debounced
}

export function EntryEditor({
  entry,
  defaultFolder,
  autoGenerate,
  onSaved,
  onCancel
}: {
  entry?: VaultEntry
  defaultFolder?: string
  autoGenerate?: boolean
  onSaved: (entry: VaultEntry) => void
  onCancel: () => void
}): React.JSX.Element {
  const queryClient = useQueryClient()
  const [form, setForm] = useState<EntryInput>(
    entry ? pickInput(entry) : { ...EMPTY, folder: defaultFolder ?? '' }
  )
  const [revealed, setRevealed] = useState(!entry)
  const set = <K extends keyof EntryInput>(key: K, value: EntryInput[K]): void =>
    setForm((prev) => ({ ...prev, [key]: value }))

  const password = useDebounced(form.password, 200)
  const { data: strength } = useQuery({
    queryKey: ['strength', password],
    queryFn: () => api.invoke('strength:check', password),
    enabled: password.length > 0,
    gcTime: 0
  })
  const { data: settings } = useQuery(queries.settings())
  const { data: entries } = useQuery(queries.entries())
  const folders = useMemo(
    () => [...new Set((entries ?? []).map((e) => e.folder).filter(Boolean))].sort(),
    [entries]
  )

  const generate = useMutation({
    mutationFn: () => api.invoke('generator:generate', settings!.generator),
    onSuccess: (result) => {
      set('password', result.password)
      setRevealed(true)
    }
  })

  const autoGenerated = useRef(false)
  useEffect(() => {
    if (autoGenerate && settings && !autoGenerated.current) {
      autoGenerated.current = true
      generate.mutate()
    }
  }, [autoGenerate, settings, generate])

  const save = useMutation({
    mutationFn: () =>
      entry ? api.invoke('entries:update', entry.id, form) : api.invoke('entries:create', form),
    onSuccess: async (saved) => {
      await queryClient.invalidateQueries({ queryKey: ['vault'] })
      toast(entry ? `Saved ${saved.title}` : `Created ${saved.title}`)
      onSaved(saved)
    }
  })

  // Window-level so the shortcuts work wherever focus is (but not while a dialog handles the key)
  useEffect(() => {
    const onKeyDown = (e: KeyboardEvent): void => {
      if (e.defaultPrevented) return
      if (isMod(e) && e.key.toLowerCase() === 's') {
        e.preventDefault()
        save.mutate()
      } else if (e.key === 'Escape') {
        e.preventDefault()
        onCancel()
      }
    }
    window.addEventListener('keydown', onKeyDown)
    return () => window.removeEventListener('keydown', onKeyDown)
  })

  return (
    <form
      className="mx-auto flex max-w-3xl flex-col gap-6 px-8 pt-8 pb-12"
      onSubmit={(e) => {
        e.preventDefault()
        save.mutate()
      }}
    >
      <header className="flex items-center gap-4">
        <Monogram title={form.title || '?'} url={form.url} size="lg" />
        <div className="min-w-0 flex-1">
          <p className="text-xs text-muted">{entry ? 'Editing' : 'New password'}</p>
          <h1 className="truncate text-2xl font-semibold tracking-tight text-bright">
            {form.title || <span className="text-faint">Untitled</span>}
          </h1>
        </div>
        <div className="flex shrink-0 items-center gap-2">
          <Button variant="ghost" onClick={onCancel}>
            Cancel
            <Kbd className="ml-1">esc</Kbd>
          </Button>
          <Button variant="primary" type="submit" disabled={save.isPending}>
            {save.isPending ? 'Saving…' : 'Save'}
            <Kbd className="ml-1 border-accent-fg/20 bg-accent-fg/10 text-accent-fg">{MOD}S</Kbd>
          </Button>
        </div>
      </header>

      <div className="grid grid-cols-2 gap-x-4 gap-y-5 rounded-xl border border-line bg-raised/60 p-5">
        <Field label="Name">
          <Input
            autoFocus
            value={form.title}
            placeholder="GitHub"
            onChange={(e) => set('title', e.target.value)}
          />
        </Field>
        <Field label="Website">
          <Input
            value={form.url}
            placeholder="https://github.com"
            className="font-mono"
            spellCheck={false}
            onChange={(e) => set('url', e.target.value)}
          />
        </Field>
        <Field label="Username" className="col-span-2">
          <Input
            value={form.username}
            placeholder="me@example.com"
            className="font-mono"
            spellCheck={false}
            autoComplete="off"
            onChange={(e) => set('username', e.target.value)}
          />
        </Field>
        <div className="col-span-2 space-y-2">
          <Field label="Password">
            <PasswordInput
              visible={revealed}
              onVisibleChange={setRevealed}
              value={form.password}
              placeholder="••••••••••••"
              onChange={(e) => set('password', e.target.value)}
              trailing={
                <Button
                  size="sm"
                  variant="ghost"
                  className="h-6 text-accent hover:text-accent"
                  onClick={() => generate.mutate()}
                  disabled={!settings || generate.isPending}
                >
                  <Wand2 className="size-3.5" />
                  Generate
                </Button>
              }
            />
          </Field>
          {form.password && strength && (
            <StrengthMeter score={strength.score} detail={`cracked in ${strength.crackTime}`} />
          )}
        </div>
        <Field label="Folder" hint="Shows up under Collections in the sidebar">
          <Input
            value={form.folder}
            list="folders"
            placeholder="None"
            onChange={(e) => set('folder', e.target.value)}
          />
          <datalist id="folders">
            {folders.map((f) => (
              <option key={f} value={f} />
            ))}
          </datalist>
        </Field>
        <Field label="Two-factor secret" hint="Optional otpauth:// URI or base32 key">
          <Input
            value={form.totp}
            placeholder="otpauth://…"
            className="font-mono"
            spellCheck={false}
            autoComplete="off"
            onChange={(e) => set('totp', e.target.value)}
          />
        </Field>
        <Field label="Notes" className="col-span-2">
          <Textarea
            value={form.notes}
            spellCheck={false}
            onChange={(e) => set('notes', e.target.value)}
          />
        </Field>
        <div className="col-span-2">
          <Checkbox
            label="Favorite"
            description="Pin to Favorites in the sidebar"
            checked={form.favorite}
            onChange={(favorite) => set('favorite', favorite)}
          />
        </div>
      </div>
      <ErrorText error={save.error} />
    </form>
  )
}

function pickInput(entry: VaultEntry): EntryInput {
  const { title, username, password, url, notes, totp, folder, favorite } = entry
  return { title, username, password, url, notes, totp, folder, favorite }
}
